# THREAT RISK SCORER
# ============================================================
def compute_threat_score(all_modules):
    """Computes 0-100 threat risk score from aggregated suspicious_indicators."""
    raw_score = 0
    for mod_data in all_modules:
        for indicator in mod_data.get("suspicious_indicators", []):
            sev = indicator.get("severity", "INFO")
            raw_score += SCORE_WEIGHTS.get(sev, 0)
    return min(raw_score, 100)


def score_to_risk_level(score):
    if score >= 75:
        return "CRITICAL"
    elif score >= 50:
        return "HIGH"
    elif score >= 25:
        return "MEDIUM"
    elif score >= 10:
        return "LOW"
    return "MINIMAL"


