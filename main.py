def check_admin():
    """Returns (is_admin: bool, privilege_label: str)."""
    is_admin = False
    try:
        if platform.system() == "Windows":
            is_admin = bool(ctypes.windll.shell32.IsUserAnAdmin())
        else:
            is_admin = (os.geteuid() == 0)
    except Exception:
        pass
    label = "Administrator (Elevated)" if is_admin else "Standard User (Non-Admin)"
    return is_admin, label


