def build_incident_timeline(all_modules, boot_time_str=None):
    """Merges chronological events from all modules into a unified timeline."""
    timeline = []
    now = datetime.datetime.now()
    now_str = now.strftime("%Y-%m-%d %H:%M:%S")

    if boot_time_str:
        timeline.append({
            "timestamp": boot_time_str,
            "source": "OS Info",
            "category": "System Boot",
            "severity": "INFO",
            "description": f"System boot recorded at: {boot_time_str}",
        })

    for mod_data in all_modules:
        mod_name = mod_data.get("module_name", "")

        # Event log forensic hits
        if "Event Log" in mod_name:
            artifacts = mod_data.get("artifacts", {})
            forensic_hits = artifacts.get("forensic_hits", {})
            for hit_key, hit_list in forensic_hits.items():
                if isinstance(hit_list, list):
                    for event in hit_list:
                        t = event.get("time_created", mod_data.get("collection_time", now_str))
                        timeline.append({
                            "timestamp": t,
                            "source": "Event Logs",
                            "category": hit_key.replace("_", " ").upper(),
                            "severity": "HIGH_RISK",
                            "description": (
                                f"EventID match [{hit_key}] on {event.get('computer', 'unknown')}"
                                f" | {', '.join(str(x) for x in event.get('event_data_summary', []))[:120]}"
                            ),
                        })
            channels = artifacts.get("channels", {})
            for channel_name, channel_data in channels.items():
                events = channel_data.get("events", []) if isinstance(channel_data, dict) else []
                for ev in events[:5]:
                    if isinstance(ev, dict):
                        timeline.append({
                            "timestamp": ev.get("time_created", ""),
                            "source": f"Event Log ({channel_name})",
                            "category": f"Level {ev.get('level', '?')} — {ev.get('level_name', '')}",
                            "severity": "INFO",
                            "description": f"[EventID {ev.get('event_id', '?')}] {ev.get('provider', '')}",
                        })

        # Flagged files from file_metadata
        if "File" in mod_name:
            artifacts = mod_data.get("artifacts", {})
            flagged = artifacts.get("flagged_files", [])
            for f in flagged[:20]:
                if isinstance(f, dict):
                    timeline.append({
                        "timestamp": f.get("modified", now_str),
                        "source": "File System",
                        "category": "FLAGGED FILE",
                        "severity": "SUSPICIOUS",
                        "description": (
                            f"{f.get('file_name', 'unknown')} | "
                            f"{', '.join(f.get('flags', []))}"
                            f" | {f.get('size_human', '')}"
                        ),
                    })

        # All suspicious indicators
        for ind in mod_data.get("suspicious_indicators", []):
            timeline.append({
                "timestamp": ind.get("timestamp", now_str),
                "source": mod_name,
                "category": f"INDICATOR [{ind.get('severity', 'INFO')}]",
                "severity": ind.get("severity", "INFO"),
                "description": f"{ind.get('indicator', '')} — {ind.get('details', '')[:150]}",
            })

    def sort_key(item):
        ts = item.get("timestamp", "")
        try:
            return datetime.datetime.strptime(ts[:19], "%Y-%m-%d %H:%M:%S")
        except Exception:
            return datetime.datetime.min

    timeline.sort(key=sort_key)
    return timeline


