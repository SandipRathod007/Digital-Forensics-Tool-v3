def load_module(module_name, base_dir):
    """Dynamically imports a forensic collector module from base_dir."""
    if base_dir not in sys.path:
        sys.path.insert(0, base_dir)
    try:
        mod = importlib.import_module(module_name)
        importlib.reload(mod)
        return mod
    except ImportError:
        return None


def run_module(module_name, base_dir):
    """Loads and runs collect_artifacts() on a module. Returns normalized dict."""
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    mod = load_module(module_name, base_dir)
    display = CONFIG["module_display_names"].get(module_name, module_name)

    if mod is None:
        return {
            "module_name": display,
            "version": "3.0",
            "status": "unavailable",
            "collection_time": now_str,
            "access_limitations": [f"Module '{module_name}.py' not found in {base_dir}"],
            "suspicious_indicators": [],
            "artifacts": {"error": f"Module file '{module_name}.py' could not be loaded."},
        }

    if not hasattr(mod, "collect_artifacts"):
        return {
            "module_name": display,
            "version": "3.0",
            "status": "unavailable",
            "collection_time": now_str,
            "access_limitations": [f"Module '{module_name}' does not expose collect_artifacts()"],
            "suspicious_indicators": [],
            "artifacts": {},
        }

    try:
        result = mod.collect_artifacts()
        if result.get("status") == "partial":
            result["status"] = "limited_access"
        result.setdefault("suspicious_indicators", [])
        result.setdefault("access_limitations", [])
        result.setdefault("version", "3.0")
        return result
    except Exception as exc:
        import traceback
        tb = traceback.format_exc()
        return {
            "module_name": display,
            "version": "3.0",
            "status": "error",
            "collection_time": now_str,
            "access_limitations": [f"Runtime error in {module_name}: {exc}"],
            "suspicious_indicators": [],
            "artifacts": {"traceback": tb},
        }


